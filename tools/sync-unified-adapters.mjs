import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const read = p => fs.readFileSync(path.join(root, p), 'utf8').replaceAll('\r', '');
function between(source, first, last) {
  const start = source.indexOf(first), end = source.indexOf(last, start + first.length);
  assert.ok(start >= 0 && end > start, 'Pinned source extraction anchors changed');
  return source.slice(start, end);
}
export function adapters() {
  const http = read('components/fakehttp/openwrt/luci-app-fakehttp/htdocs/luci-static/resources/view/fakehttp.js');
  const sip = read('components/fakesip/openwrt/luci-app-fakesip/root/www/luci-static/resources/view/fakesip/fakesip.js');
  const header = "// Generated by tools/sync-unified-adapters.mjs; do not edit.\n// SPDX-License-Identifier: GPL-3.0-or-later\n'use strict';\n'require baseclass';\n'require form';\n'require tools.widgets as widgets';\n";
  let httpFields = between(http, "\t\ts = m.section(form.TypedSection", '\t\treturn getStatus()');
  httpFields = httpFields.replace("'globals', _('General')", "'globals', _('TCP — General')")
    .replace("'payload', _('Payloads')", "'payload', _('TCP — Payloads')")
    .replace("'advanced', 'advanced', _('Advanced')", "'advanced', 'advanced', _('TCP — Advanced')");
  let sipHelpers = between(sip, 'function asList(', 'function sleep(');
  sipHelpers = sipHelpers.replace(between(sip, 'function parseServiceStatus(', 'function parseUint32('), '')
    .replace(between(sip, 'function notifyServiceSuccess(', 'function revalidate('), '');
  let sipFields = between(sip, "\t\ts = m.section(form.NamedSection, 'main'", '\t\treturn m.render().then(');
  sipFields = sipFields.replaceAll("get('fakesip',", "get('faketraffic',")
    .replace("'main', 'fakesip', _('Configuration')", "'main', 'fakesip', _('UDP — Configuration')");
  const httpInit = read('components/fakehttp/openwrt/fakehttp/files/etc/init.d/fakehttp');
  const sipInit = read('components/fakesip/openwrt/fakesip/files/fakesip.init');
  const tcp = between(httpInit, 'append_flag()', 'reload_service()')
    .replace('start_service()', 'start_tcp()')
    .replace('\tnetwork_flush_cache\n\tconfig_load "$NAME"\n', '')
    .replace('procd_open_instance\n', 'procd_open_instance tcp\n')
    .replace('"$PROG"', '/usr/libexec/faketraffic/fakehttp')
    .replace('\tprocd_set_param respawn\n', '\tprocd_set_param respawn 3600 5 5\n\tprocd_set_param term_timeout 15\n');
  const udp = between(sipInit, 'append_bool_arg()', 'start_service()')
    .replace('start_instance()', 'start_udp()')
    .replace('procd_open_instance "$section"', 'procd_open_instance udp')
    .replace('"$PROG"', '/usr/libexec/faketraffic/fakesip')
    .replaceAll('logger -t fakesip', 'logger -t faketraffic');
  const init = `#!/bin/sh /etc/rc.common
# Generated by tools/sync-unified-adapters.mjs; do not edit.
# SPDX-License-Identifier: GPL-3.0-or-later
START=99
STOP=10
USE_PROCD=1
. /lib/functions.sh
. /lib/functions/network.sh

${tcp}
${udp}
# Never compete with a still-active/enabled legacy owner.
legacy_active() {
    local old
    for old in fakehttp fakesip; do
        [ -x "/etc/init.d/$old" ] || continue
        if "/etc/init.d/$old" running >/dev/null 2>&1 ||
           "/etc/init.d/$old" enabled >/dev/null 2>&1; then
            logger -t faketraffic "legacy service $old must be stopped and disabled before migration"
            return 0
        fi
    done
    return 1
}

start_service() {
    local tcp_enabled udp_enabled tcp_queue udp_queue
    legacy_active && return 1
    network_flush_cache
    config_load faketraffic
    config_get_bool tcp_enabled globals enabled 0
    config_get_bool udp_enabled main enabled 0
    config_get tcp_queue advanced queue_number 512
    config_get udp_queue main queue_num 513
    [ "$tcp_queue" != -1 ] || tcp_queue=512
    if [ "$tcp_enabled" = 1 ] && [ "$udp_enabled" = 1 ] &&
       [ "$tcp_queue" -eq "$udp_queue" ] 2>/dev/null; then
        logger -t faketraffic "TCP and UDP cannot share one NFQUEUE"
        return 1
    fi
    start_tcp
    start_udp main
    return 0
}

add_network_trigger() {
    [ -n "$1" ] && procd_add_interface_trigger "interface.*" "$1" /etc/init.d/faketraffic reload
}

service_triggers() {
    procd_add_reload_trigger faketraffic
    config_load faketraffic
    config_list_foreach globals interface add_network_trigger
    config_list_foreach main network add_network_trigger
}
# No custom reload_service: rc.common submits instance definitions to procd,
# which compares argv and preserves an unchanged engine.
`;
  return new Map([
    ['openwrt/luci-app-faketraffic/root/www/luci-static/resources/faketraffic/tcp.js', header + between(http, 'function validatePayload(', 'return view.extend(') + '\nreturn baseclass.extend({\n\taddFields: function(m) {\n\t\tvar s, o;\n' + httpFields + '\t}\n});\n'],
    ['openwrt/luci-app-faketraffic/root/www/luci-static/resources/faketraffic/udp.js', header + sipHelpers + '\nreturn baseclass.extend({\n\taddFields: function(m) {\n\t\tvar s, o, enabledOption, modeOption, networkOption, interfaceOption, allInterfacesOption;\n\t\tvar outboundOption, inboundOption, ipv4Option, ipv6Option;\n\t\tvar markOption, maskOption, dynamicOption, noHopOption, profileOption, sipUriOption;\n' + sipFields + '\t}\n});\n'],
    ['openwrt/faketraffic/files/etc/init.d/faketraffic', init],
    ['openwrt/faketraffic/files/etc/config/faketraffic', '# One faketraffic service manages TCP and UDP.\n' + read('components/fakehttp/openwrt/fakehttp/files/etc/config/fakehttp') + '\n' + read('components/fakesip/openwrt/fakesip/files/fakesip.config')]
  ]);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [rel, source] of adapters()) {
    const file = path.join(root, rel);
    if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8'), source, 'Adapter drift: ' + rel);
    else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, source); }
  }
  console.log('Four pinned-source adapters verified/generated');
}
